'use client';

import React, { useState } from 'react';
import { 
  TrendingUp, 
  CheckCircle2, 
  XCircle, 
  Flame, 
  Calendar, 
  Sparkles, 
  MessageSquare, 
  Clock, 
  Plus, 
  ChevronRight, 
  ShieldCheck, 
  Send,
  X
} from 'lucide-react';
import { 
  ResponsiveContainer, 
  AreaChart, 
  Area, 
  XAxis, 
  YAxis, 
  Tooltip, 
  CartesianGrid, 
  BarChart, 
  Bar 
} from 'recharts';
import { apiSubmitCheckIn } from '@/lib/api';

interface ProgressViewProps {
  stats: any;
  history: any[];
  summaries: any[];
  onCheckInCompleted: () => void;
}

export default function ProgressView({
  stats,
  history,
  summaries,
  onCheckInCompleted,
}: ProgressViewProps) {
  const [showCheckInModal, setShowCheckInModal] = useState(false);
  const [condition, setCondition] = useState('Improving');
  const [feedback, setFeedback] = useState('');
  const [isSubmitting, setIsSubmitting] = useState(false);

  const weeklyAdherence = stats?.weekly_adherence || 85;
  const totalCompleted = stats?.total_completed_this_week || 14;
  const totalMissed = stats?.total_missed_this_week || 2;
  const streak = stats?.current_streak_days || 4;

  const chartData = history && history.length > 0 ? history : [
    { day: 'Mon', adherence: 80, completed: 2, total: 2 },
    { day: 'Tue', adherence: 100, completed: 2, total: 2 },
    { day: 'Wed', adherence: 100, completed: 2, total: 2 },
    { day: 'Thu', adherence: 50, completed: 1, total: 2 },
    { day: 'Fri', adherence: 100, completed: 2, total: 2 },
    { day: 'Sat', adherence: 100, completed: 2, total: 2 },
    { day: 'Sun', adherence: 100, completed: 2, total: 2 },
  ];

  const handleSubmitCheckIn = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!feedback.trim()) return;

    setIsSubmitting(true);
    try {
      await apiSubmitCheckIn(feedback, condition);
      setShowCheckInModal(false);
      setFeedback('');
      onCheckInCompleted();
    } catch (err: any) {
      alert(`Error submitting check-in: ${err.message}`);
    } finally {
      setIsSubmitting(false);
    }
  };

  return (
    <div className="space-y-6 md:space-y-8 animate-fadeIn">
      {/* Header */}
      <div className="bg-white rounded-xl border border-[#E3E8E1] p-6 md:p-8 shadow-card flex flex-col md:flex-row md:items-center justify-between gap-6">
        <div>
          <div className="flex items-center space-x-2 mb-2">
            <span className="px-3 py-1 rounded-full bg-[#EDF3ED] text-[#173F35] text-xs font-bold border border-[#D0DDD0] flex items-center space-x-1">
              <TrendingUp className="w-3.5 h-3.5 text-[#477C68]" />
              <span>Adherence Analytics</span>
            </span>
          </div>
          <h1 className="text-2xl md:text-3xl font-bold text-[#173F35]">
            Habit Consistency &amp; Clinical Progress
          </h1>
          <p className="text-sm text-[#727B74] mt-1.5 max-w-xl leading-relaxed">
            Monitor regimen adherence trajectory, track missed applications, and review weekly progress summaries generated by the Progress Agent.
          </p>
        </div>

        <button
          onClick={() => setShowCheckInModal(true)}
          className="px-4 py-2.5 rounded-lg bg-[#173F35] hover:bg-[#1F4F43] text-white text-xs md:text-sm font-semibold flex items-center space-x-2 transition-all shadow-sm self-start md:self-center"
        >
          <Sparkles className="w-4 h-4 text-[#A8BDA9]" />
          <span>Weekly Check-in</span>
        </button>
      </div>

      {/* 4 Metric Cards */}
      <div className="grid grid-cols-2 lg:grid-cols-4 gap-4">
        <div className="bg-white p-5 rounded-xl border border-[#E3E8E1] shadow-card">
          <p className="text-xs font-medium text-[#727B74] uppercase tracking-wide">Weekly Adherence</p>
          <div className="flex items-baseline space-x-2 mt-1">
            <span className="text-2xl md:text-3xl font-bold text-[#173F35]">{weeklyAdherence}%</span>
            <span className="text-xs text-[#2F855A] font-semibold">Good Pace</span>
          </div>
        </div>

        <div className="bg-white p-5 rounded-xl border border-[#E3E8E1] shadow-card">
          <p className="text-xs font-medium text-[#727B74] uppercase tracking-wide">Steps Completed</p>
          <div className="flex items-baseline space-x-2 mt-1">
            <span className="text-2xl md:text-3xl font-bold text-[#173F35]">{totalCompleted}</span>
            <span className="text-xs text-[#727B74]">this week</span>
          </div>
        </div>

        <div className="bg-white p-5 rounded-xl border border-[#E3E8E1] shadow-card">
          <p className="text-xs font-medium text-[#727B74] uppercase tracking-wide">Steps Missed</p>
          <div className="flex items-baseline space-x-2 mt-1">
            <span className="text-2xl md:text-3xl font-bold text-[#B7791F]">{totalMissed}</span>
            <span className="text-xs text-[#727B74]">recovered</span>
          </div>
        </div>

        <div className="bg-white p-5 rounded-xl border border-[#E3E8E1] shadow-card">
          <p className="text-xs font-medium text-[#727B74] uppercase tracking-wide">Active Streak</p>
          <div className="flex items-baseline space-x-2 mt-1">
            <span className="text-2xl md:text-3xl font-bold text-[#173F35]">{streak}</span>
            <span className="text-xs text-[#727B74]">days consistent</span>
          </div>
        </div>
      </div>

      {/* Analytics Charts Grid */}
      <div className="grid grid-cols-1 lg:grid-cols-2 gap-6">
        {/* Adherence Trajectory Area Chart */}
        <div className="bg-white p-6 rounded-xl border border-[#E3E8E1] shadow-card">
          <div className="flex items-center justify-between mb-4">
            <h3 className="text-sm font-bold text-[#173F35]">7-Day Adherence Trajectory</h3>
            <span className="text-xs font-semibold px-2 py-0.5 rounded bg-[#EDF3ED] text-[#173F35]">
              Target: 80%+
            </span>
          </div>

          <div className="h-64 w-full">
            <ResponsiveContainer width="100%" height="100%">
              <AreaChart data={chartData} margin={{ top: 10, right: 10, left: -20, bottom: 0 }}>
                <defs>
                  <linearGradient id="sageAreaGrad" x1="0" y1="0" x2="0" y2="1">
                    <stop offset="5%" stopColor="#173F35" stopOpacity={0.4} />
                    <stop offset="50%" stopColor="#477C68" stopOpacity={0.2} />
                    <stop offset="95%" stopColor="#A8BDA9" stopOpacity={0.0} />
                  </linearGradient>
                </defs>
                <CartesianGrid strokeDasharray="3 3" stroke="#E3E8E1" vertical={false} />
                <XAxis dataKey="day" stroke="#727B74" fontSize={11} tickLine={false} />
                <YAxis stroke="#727B74" fontSize={11} domain={[0, 100]} tickLine={false} unit="%" />
                <Tooltip
                  contentStyle={{
                    backgroundColor: '#FFFFFF',
                    border: '1px solid #E3E8E1',
                    borderRadius: '8px',
                    fontSize: '12px',
                    boxShadow: '0 2px 8px rgba(0,0,0,0.06)',
                  }}
                  formatter={(val: any) => [`${val}%`, 'Adherence']}
                />
                <Area
                  type="monotone"
                  dataKey="adherence"
                  stroke="#173F35"
                  strokeWidth={2.5}
                  fillOpacity={1}
                  fill="url(#sageAreaGrad)"
                />
              </AreaChart>
            </ResponsiveContainer>
          </div>
        </div>

        {/* Daily Completed Tasks Bar Chart */}
        <div className="bg-white p-6 rounded-xl border border-[#E3E8E1] shadow-card">
          <div className="flex items-center justify-between mb-4">
            <h3 className="text-sm font-bold text-[#173F35]">Daily Completed Tasks</h3>
            <span className="text-xs text-[#727B74]">Morning vs Evening</span>
          </div>

          <div className="h-64 w-full">
            <ResponsiveContainer width="100%" height="100%">
              <BarChart data={chartData} margin={{ top: 10, right: 10, left: -20, bottom: 0 }}>
                <CartesianGrid strokeDasharray="3 3" stroke="#E3E8E1" vertical={false} />
                <XAxis dataKey="day" stroke="#727B74" fontSize={11} tickLine={false} />
                <YAxis stroke="#727B74" fontSize={11} tickLine={false} allowDecimals={false} />
                <Tooltip
                  contentStyle={{
                    backgroundColor: '#FFFFFF',
                    border: '1px solid #E3E8E1',
                    borderRadius: '8px',
                    fontSize: '12px',
                    boxShadow: '0 2px 8px rgba(0,0,0,0.06)',
                  }}
                  formatter={(val: any) => [val, 'Completed Tasks']}
                />
                <Bar dataKey="completed" fill="#477C68" radius={[4, 4, 0, 0]} />
              </BarChart>
            </ResponsiveContainer>
          </div>
        </div>
      </div>

      {/* Actionable Dermatologist Tips & Weekly AI Insights */}
      <div className="bg-gradient-to-br from-[#FAF9F5] via-[#EDF3ED]/40 to-white rounded-xl border border-[#D0DDD0] p-6 shadow-card">
        <div className="flex items-start space-x-3.5">
          <div className="w-10 h-10 rounded-lg bg-[#173F35] text-white flex items-center justify-center flex-shrink-0 shadow-xs">
            <Sparkles className="w-5 h-5 text-[#A8BDA9]" />
          </div>
          <div className="flex-1">
            <div className="flex items-center space-x-2">
              <h3 className="text-sm font-bold text-[#173F35]">Clinical Dermatologist Insights &amp; Active Protocol</h3>
              <span className="text-[10px] font-bold uppercase tracking-wider px-2 py-0.5 rounded bg-[#EDF3ED] text-[#2F855A] border border-[#D0DDD0]">
                Verified Care Model
              </span>
            </div>
            <p className="text-xs text-[#252D29] mt-1.5 leading-relaxed">
              Based on your <strong>{weeklyAdherence}% weekly consistency</strong> and active habit trajectory, follicular and epidermal cellular response is progressing within normal parameters.
            </p>
            <div className="mt-3.5 grid grid-cols-1 sm:grid-cols-2 gap-3 text-xs">
              <div className="p-3 rounded-lg bg-white border border-[#E3E8E1] space-y-1">
                <span className="text-[10px] font-bold uppercase tracking-wider text-[#477C68] block">Dermatologist Tip #1</span>
                <p className="text-[#727B74] leading-relaxed">Allow active serums (Salicylic Acid / Redensyl) 90–120 seconds to fully absorb before applying hydrators or barrier cremes.</p>
              </div>
              <div className="p-3 rounded-lg bg-white border border-[#E3E8E1] space-y-1">
                <span className="text-[10px] font-bold uppercase tracking-wider text-[#477C68] block">Dermatologist Tip #2</span>
                <p className="text-[#727B74] leading-relaxed">Consistency beats intensity: missing a single dose is completely fine, but never double-apply actives on the next day.</p>
              </div>
            </div>
          </div>
        </div>
      </div>

      {/* AI-Generated Weekly Summaries */}
      <div className="bg-white rounded-xl border border-[#E3E8E1] p-6 shadow-card">
        <div className="flex items-center justify-between mb-5">
          <div>
            <h3 className="text-base font-bold text-[#173F35]">AI Progress Evaluations</h3>
            <p className="text-xs text-[#727B74]">Weekly qualitative summaries synthesized by our Progress Agent.</p>
          </div>
          <span className="text-xs font-semibold px-2.5 py-1 rounded bg-[#EDF3ED] text-[#173F35] border border-[#D0DDD0]">
            {summaries.length} Historical Reviews
          </span>
        </div>

        {summaries.length === 0 ? (
          <div className="text-center py-10 bg-[#FAF9F5] rounded-xl border border-dashed border-[#D0DDD0]">
            <MessageSquare className="w-8 h-8 text-[#A8BDA9] mx-auto mb-2" />
            <p className="text-sm font-bold text-[#173F35]">No weekly summaries logged yet</p>
            <p className="text-xs text-[#727B74] mt-1 mb-4">Complete your first weekly check-in to generate clinical AI feedback.</p>
            <button
              onClick={() => setShowCheckInModal(true)}
              className="px-4 py-2 rounded-lg bg-[#173F35] text-white text-xs font-semibold hover:bg-[#1F4F43]"
            >
              Start First Check-in
            </button>
          </div>
        ) : (
          <div className="space-y-4">
            {summaries.map((summary) => (
              <div
                key={summary.id}
                className="p-5 rounded-xl bg-[#FAF9F5] border border-[#E3E8E1] space-y-3"
              >
                <div className="flex items-center justify-between">
                  <div className="flex items-center space-x-2">
                    <span className="font-bold text-sm text-[#173F35]">{summary.week_label}</span>
                    <span className="text-[11px] font-semibold px-2 py-0.5 rounded-full bg-[#EDF3ED] text-[#2F855A] border border-[#D0DDD0]">
                      Adherence: {summary.adherence_score}%
                    </span>
                  </div>
                  <span className="text-xs text-[#727B74]">
                    {new Date(summary.created_at).toLocaleDateString()}
                  </span>
                </div>

                <p className="text-xs text-[#252D29] leading-relaxed">
                  {summary.summary_text}
                </p>

                {summary.recommendations && (
                  <div className="p-3 bg-white rounded-lg border border-[#E3E8E1] text-xs">
                    <span className="font-bold text-[#173F35] block mb-1">Agent Action Recommendations:</span>
                    <p className="text-[#727B74] whitespace-pre-line leading-relaxed">{summary.recommendations}</p>
                  </div>
                )}
              </div>
            ))}
          </div>
        )}
      </div>

      {/* Weekly Check-in Modal */}
      {showCheckInModal && (
        <div className="fixed inset-0 z-50 bg-black/40 backdrop-blur-sm flex items-center justify-center p-4">
          <div className="bg-white rounded-xl border border-[#E3E8E1] shadow-card max-w-lg w-full p-6 animate-fadeIn">
            <div className="flex items-start justify-between pb-3 mb-4 border-b border-[#E3E8E1]">
              <div>
                <h3 className="text-base font-bold text-[#173F35]">Log Weekly Check-in</h3>
                <p className="text-xs text-[#727B74]">Help the AI evaluate your personal-care routine response</p>
              </div>
              <button
                onClick={() => setShowCheckInModal(false)}
                className="text-[#727B74] hover:text-[#173F35]"
              >
                <X className="w-5 h-5" />
              </button>
            </div>

            <form onSubmit={handleSubmitCheckIn} className="space-y-4">
              <div>
                <label className="block text-xs font-bold text-[#173F35] uppercase tracking-wider mb-1.5">
                  How does your skin / hair feel compared to last week?
                </label>
                <div className="grid grid-cols-3 gap-2">
                  {['Improving', 'Unchanged', 'Irritated'].map((val) => (
                    <button
                      type="button"
                      key={val}
                      onClick={() => setCondition(val)}
                      className={`py-2 px-3 rounded-lg text-xs font-semibold border transition-all ${
                        condition === val
                          ? 'bg-[#173F35] text-white border-[#173F35]'
                          : 'bg-[#FAF9F5] text-[#727B74] border-[#E3E8E1] hover:bg-[#EDF3ED]'
                      }`}
                    >
                      {val}
                    </button>
                  ))}
                </div>
              </div>

              <div>
                <label className="block text-xs font-bold text-[#173F35] uppercase tracking-wider mb-1.5">
                  Weekly Observations &amp; Notes
                </label>
                <textarea
                  rows={4}
                  required
                  placeholder="e.g. Scalp feels less itchy, hair shedding in the shower has visibly reduced, experienced no flaking..."
                  value={feedback}
                  onChange={(e) => setFeedback(e.target.value)}
                  className="w-full p-3 rounded-lg bg-[#FAF9F5] border border-[#E3E8E1] text-xs text-[#252D29] placeholder-[#727B74] focus:outline-none focus:border-[#173F35] focus:bg-white transition-all"
                />
              </div>

              <div className="pt-3 border-t border-[#E3E8E1] flex justify-end space-x-2">
                <button
                  type="button"
                  onClick={() => setShowCheckInModal(false)}
                  className="px-4 py-2 rounded-lg bg-[#FAF9F5] text-[#727B74] hover:text-[#173F35] text-xs font-semibold border border-[#E3E8E1]"
                >
                  Cancel
                </button>
                <button
                  type="submit"
                  disabled={isSubmitting || !feedback.trim()}
                  className="px-4 py-2 rounded-lg bg-[#173F35] hover:bg-[#1F4F43] disabled:opacity-50 text-white text-xs font-semibold flex items-center space-x-1.5"
                >
                  <Sparkles className="w-3.5 h-3.5 text-[#A8BDA9]" />
                  <span>{isSubmitting ? 'Evaluating with AI...' : 'Submit Evaluation'}</span>
                </button>
              </div>
            </form>
          </div>
        </div>
      )}
    </div>
  );
}
